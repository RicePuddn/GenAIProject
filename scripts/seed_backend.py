# Foreign-key order: parent records are inserted before their related rows.
SEED_TABLES = {
    "products": (PRODUCTS_COLUMNS, PRODUCTS),
    "customers": (CUSTOMERS_COLUMNS, CUSTOMERS),
    "orders": (ORDERS_COLUMNS, ORDERS),
    "order_items": (ORDER_ITEMS_COLUMNS, ORDER_ITEMS),
    "shipments": (SHIPMENTS_COLUMNS, SHIPMENTS),
    "shipment_items": (SHIPMENT_ITEMS_COLUMNS, SHIPMENT_ITEMS),
    "shipment_events": (SHIPMENT_EVENTS_COLUMNS, SHIPMENT_EVENTS),
    "payments": (PAYMENTS_COLUMNS, PAYMENTS),
    "returns": (RETURNS_COLUMNS, RETURNS),
    "return_items": (RETURN_ITEMS_COLUMNS, RETURN_ITEMS),
    "refunds": (REFUNDS_COLUMNS, REFUNDS),
    "support_tickets": (SUPPORT_TICKETS_COLUMNS, SUPPORT_TICKETS),
}


# Name every inserted column and preserve records that already exist.
def insert_record(cur, table: str, **record) -> None:
    query = sql.SQL("INSERT INTO {} ({}) VALUES ({}) ON CONFLICT DO NOTHING").format(
        sql.Identifier(table),
        sql.SQL(", ").join(map(sql.Identifier, record)),
        sql.SQL(", ").join(sql.Placeholder() for _ in record),
    )
    cur.execute(query, tuple(record.values()))


# Insert the rows above; address dictionaries are PostgreSQL JSONB values.
def seed_records(cur) -> None:
    for table, (columns, rows) in SEED_TABLES.items():
        for values in rows:
            record = dict(zip(columns, values, strict=True))
            record = {key: Jsonb(value) if isinstance(value, dict) else value for key, value in record.items()}
            insert_record(cur, table, **record)


# Create missing tables from schema.sql, then insert the same records on every run.
def seed(dsn: str, *, reset: bool = False) -> None:
    """Create the tables and insert the seed rows; `reset` first deletes everything, including agent writes."""
    with psycopg.connect(dsn, connect_timeout=5) as conn, conn.cursor() as cur:
        cur.execute((ROOT / "data/backend_seed/schema.sql").read_text())
        if reset:
            tables = [sql.Identifier(table) for table in (*SEED_TABLES, "backend_writes")]
            cur.execute(sql.SQL("TRUNCATE {} CASCADE").format(sql.SQL(", ").join(tables)))
        seed_records(cur)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reset", action="store_true",
                        help="delete all rows first, so agent writes from earlier runs are gone")
    args = parser.parse_args()
    load_env()
    dsn = os.environ.get("SUPPORT_OPS_DATABASE_URL")
    if not dsn:
        raise RuntimeError("set SUPPORT_OPS_DATABASE_URL in .env (see .env.example)")
    seed(dsn, reset=args.reset)
    print("Seeded background data and 10 labelled evaluation scenarios. "
          + ("All earlier rows were deleted." if args.reset else "Existing rows were preserved."))


if __name__ == "__main__":
    main()
